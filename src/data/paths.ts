/**
 * Utilitários de consulta
 */
export function getPath(pathId: CharacterPathId): CharacterPathDefinition {
  return PATHS_CATALOG[pathId];
}

export function getPathsForCharacter(characterId: string): CharacterPathDefinition[] {
  return Object.values(PATHS_CATALOG).filter(p => p.characterId === characterId);
}

export function getSubPath(pathId: CharacterPathId, subPathId: string): SubPathDefinition | undefined {
  return PATHS_CATALOG[pathId]?.subPaths.find(s => s.id === subPathId);
}

export function getSubSkill(subSkillId: string) {
  for (const path of Object.values(PATHS_CATALOG)) {
    const skill = path.subSkills.find(s => s.id === subSkillId);
    if (skill) return skill;
  }
  return undefined;
}

/**
 * Conjunto de todos os status de caminho implementados (utilizado em auditoria/testes)
 */
export const ALL_PATH_STATUSES: PathSpecificStatusType[] = Array.from(
  new Set(
    Object.values(PATHS_CATALOG).flatMap(p => [
      p.signatureStatus,
      ...p.subPaths.map(s => s.grantedStatus).filter((s): s is PathSpecificStatusType => Boolean(s)),
      ...p.subSkills.map(s => s.inflictedStatus).filter((s): s is PathSpecificStatusType => Boolean(s)),
    ])
  )
);
