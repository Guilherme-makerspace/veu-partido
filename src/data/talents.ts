/**
 * Validação de pré-requisitos de atributos para desbloqueio
 */
export function meetsTalentRequirements(stats: BaseStats, req: Partial<BaseStats>): boolean {
  for (const [key, val] of Object.entries(req)) {
    if (val === undefined) continue;
    const statKey = key as keyof BaseStats;
    if ((stats[statKey] || 0) < (val || 0)) {
      return false;
    }
  }
  return true;
}

/**
 * Consulta talentos permitidos para um caminho específico
 */
export function getTalentsForPath(pathId: string): TalentCard[] {
  return TALENTS_CATALOG.filter(t => !t.allowedPaths || t.allowedPaths.includes(pathId as any));
}

/**
 * Consulta talentos por tier
 */
export function getTalentsByTier(tier: TalentCard['tier']): TalentCard[] {
  return TALENTS_CATALOG.filter(t => t.tier === tier);
}
