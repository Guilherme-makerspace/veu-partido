export function createEnemyConfig(type, level = 1) {
  const base = ENEMY_CONFIGS[type] || ENEMY_CONFIGS.fragmentado;
  const scale = 1 + (level - 1) * 0.15;
  return {
    ...base,
    pulso: Math.floor(base.pulso * scale),
    fratura: Math.floor(base.fratura * scale),
    scoreValue: Math.floor(base.scoreValue * scale),
  };
}
